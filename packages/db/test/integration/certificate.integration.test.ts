import { afterAll, beforeAll, describe, expect, test } from "vitest";
import { withDatabase, type TestDatabase } from "./helpers";

let database: TestDatabase;

beforeAll(async () => {
  database = await withDatabase();
});

afterAll(async () => {
  await database.close();
});

const unique = () => Math.random().toString(36).slice(2);

const sha256 = "a".repeat(64);

const createEnrollment = async () => {
  const student = await database.prisma.user.create({
    data: {
      email: `${unique()}@example.com`,
      passwordHash: "argon2id-hash",
      role: "STUDENT",
      realm: "STUDENT",
    },
  });
  const course = await database.prisma.course.create({
    data: { slug: `course-${unique()}`, title: "Gender safety" },
  });
  const revision = await database.prisma.courseRevision.create({
    data: { courseId: course.id, number: 1 },
  });
  return database.prisma.enrollment.create({
    data: {
      userId: student.id,
      courseId: course.id,
      courseRevisionId: revision.id,
      status: "COMPLETED",
    },
  });
};

const certificateData = (enrollmentId: string) => ({
  enrollmentId,
  recipientName: "Ayesha Rahman",
  fileKey: `certificates/${unique()}.pdf`,
  fileSha256: sha256,
});

describe("one certificate per enrollment", () => {
  test("a second certificate for the same enrollment is rejected", async () => {
    const enrollment = await createEnrollment();
    await database.prisma.certificate.create({ data: certificateData(enrollment.id) });

    await expect(
      database.prisma.certificate.create({ data: certificateData(enrollment.id) }),
    ).rejects.toMatchObject({ code: "P2002" });
  });

  test("an issued certificate keeps the name it was printed with and is not revoked", async () => {
    const enrollment = await createEnrollment();

    const certificate = await database.prisma.certificate.create({
      data: certificateData(enrollment.id),
    });

    expect(certificate.recipientName).toBe("Ayesha Rahman");
    expect(certificate.issuedAt).toBeInstanceOf(Date);
    expect(certificate.revokedAt).toBeNull();
  });

  test("an enrollment with a certificate cannot be hard deleted", async () => {
    const enrollment = await createEnrollment();
    await database.prisma.certificate.create({ data: certificateData(enrollment.id) });

    await expect(
      database.hardDeleting.enrollment.delete({ where: { id: enrollment.id } }),
    ).rejects.toMatchObject({ code: "P2003" });
  });
});

describe("certificate numbers", () => {
  test("each number is generated by the database in a fixed format", async () => {
    const enrollment = await createEnrollment();

    const certificate = await database.prisma.certificate.create({
      data: certificateData(enrollment.id),
    });

    expect(certificate.number).toMatch(/^[0-9A-F]{16}$/);
  });

  test("numbers are random and not sequential", async () => {
    const numbers: string[] = [];
    for (let index = 0; index < 5; index += 1) {
      const enrollment = await createEnrollment();
      const certificate = await database.prisma.certificate.create({
        data: certificateData(enrollment.id),
      });
      numbers.push(certificate.number);
    }

    expect(new Set(numbers).size).toBe(5);
    const values = numbers.map((number) => BigInt(`0x${number}`));
    const steps = values.slice(1).map((value, index) => value - values[index]!);
    expect(steps.every((step) => step === 1n)).toBe(false);
    expect(steps.every((step) => step > 0n)).toBe(false);
  });

  test("two certificates cannot share a number", async () => {
    const first = await createEnrollment();
    const second = await createEnrollment();
    const issued = await database.prisma.certificate.create({ data: certificateData(first.id) });

    await expect(
      database.prisma.certificate.create({
        data: { ...certificateData(second.id), number: issued.number },
      }),
    ).rejects.toMatchObject({ code: "P2002" });
  });

  test("a number in another format is rejected", async () => {
    const enrollment = await createEnrollment();

    await expect(
      database.prisma.certificate.create({
        data: { ...certificateData(enrollment.id), number: "123" },
      }),
    ).rejects.toThrow(/Certificate_number_format_check/);
  });
});

describe("file checksum", () => {
  test("a checksum that is not 64 hex characters is rejected", async () => {
    const enrollment = await createEnrollment();

    await expect(
      database.prisma.certificate.create({
        data: { ...certificateData(enrollment.id), fileSha256: "not-a-hash" },
      }),
    ).rejects.toThrow(/Certificate_fileSha256_sha256_check/);
  });
});

describe("issued certificates are immutable", () => {
  test.each([
    ["number", { number: "0000000000000000" }],
    ["recipientName", { recipientName: "Someone Else" }],
    ["fileKey", { fileKey: "certificates/other.pdf" }],
    ["fileSha256", { fileSha256: "b".repeat(64) }],
  ])("%s cannot change", async (_name, change) => {
    const enrollment = await createEnrollment();
    const certificate = await database.prisma.certificate.create({
      data: certificateData(enrollment.id),
    });

    await expect(
      database.prisma.certificate.update({ where: { id: certificate.id }, data: change }),
    ).rejects.toThrow(/issued certificate/);

    const stored = await database.prisma.certificate.findUniqueOrThrow({
      where: { id: certificate.id },
    });
    expect(stored).toMatchObject({
      number: certificate.number,
      recipientName: certificate.recipientName,
      fileKey: certificate.fileKey,
      fileSha256: certificate.fileSha256,
    });
  });

  test("a certificate can still be revoked and the revocation lifted", async () => {
    const enrollment = await createEnrollment();
    const certificate = await database.prisma.certificate.create({
      data: certificateData(enrollment.id),
    });

    const revoked = await database.prisma.certificate.update({
      where: { id: certificate.id },
      data: { revokedAt: new Date() },
    });
    const restored = await database.prisma.certificate.update({
      where: { id: certificate.id },
      data: { revokedAt: null },
    });

    expect(revoked.revokedAt).toBeInstanceOf(Date);
    expect(restored.revokedAt).toBeNull();
  });
});
